function samplesFor(edge: TornEdge, variant: TornVariant, torn: boolean) {
  if (!torn) return WOBBLE
  if (edge === 'top') return TORN_TOP[variant]
  if (edge === 'bottom') return TORN_BOTTOM[variant]
  if (edge === 'left') return TORN_LEFT[variant]
  return TORN_RIGHT[variant]
}

function mapEdge(
  edge: TornEdge,
  samples: Sample[],
  intensity: number,
): Array<[number, number]> {
  return samples.map(({ t, inset }) => {
    const depth = inset * intensity
    if (edge === 'top') return [t, depth]
    if (edge === 'bottom') return [1 - t, 1 - depth]
    if (edge === 'right') return [1 - depth, t]
    return [depth, 1 - t]
  })
}

export function tornSheetPath(
  edges: TornEdge[],
  variant: TornVariant = 1,
  intensity: TornIntensity = 'medium',
) {
  const scale = INTENSITY[intensity]
  const torn = new Set(edges)
  const top = mapEdge('top', samplesFor('top', variant, torn.has('top')), scale)
  const right = mapEdge('right', samplesFor('right', variant, torn.has('right')), scale)
  const bottom = mapEdge('bottom', samplesFor('bottom', variant, torn.has('bottom')), scale)
  const left = mapEdge('left', samplesFor('left', variant, torn.has('left')), scale)
  const pts = [...top, ...right, ...bottom, ...left]
  const [x0, y0] = pts[0]
  const line = pts
    .slice(1)
    .map(([x, y]) => `L${x.toFixed(4)} ${y.toFixed(4)}`)
    .join('')
  return `M${x0.toFixed(4)} ${y0.toFixed(4)}${line}Z`
}
